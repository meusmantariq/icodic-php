<?php
/**
 * build_seed.php — converts the Base44 CSV / JSON exports into database/seed.sql
 * and downloads every referenced media.base44.com image into public_html/uploads/migrated/.
 *
 * Usage (CLI):  php database/build_seed.php /path/to/exports
 * The exports folder must contain the *_export.csv files and optional <Entity>.json files.
 * Re-running is safe: it rewrites seed.sql and skips already-downloaded images.
 */
declare(strict_types=1);

$src = $argv[1] ?? (__DIR__ . '/source');
$root = dirname(__DIR__);
$uploadDir = $root . '/public_html/uploads/migrated';
@mkdir($uploadDir, 0755, true);
$out = [];
$imageMap = [];

function readCsv(string $path): array {
    if (!is_file($path)) return [];
    $fh = fopen($path, 'r');
    $head = fgetcsv($fh);
    $rows = [];
    while (($r = fgetcsv($fh)) !== false) {
        if (count($r) === 1 && $r[0] === null) continue;
        $rows[] = array_combine($head, $r);
    }
    fclose($fh);
    return $rows;
}
function findFile(string $dir, string $entity): ?string {
    foreach (glob("$dir/*{$entity}_export.csv") ?: [] as $f) return $f;
    return null;
}
function loadEntity(string $dir, string $entity): array {
    $csv = findFile($dir, $entity);
    if ($csv) return readCsv($csv);
    $json = "$dir/$entity.json";
    if (is_file($json)) return json_decode(file_get_contents($json), true) ?: [];
    return [];
}
function q($v): string {
    if ($v === null || $v === '') return 'NULL';
    if (is_bool($v)) return $v ? '1' : '0';
    if (is_int($v) || is_float($v)) return (string)$v;
    return "'" . str_replace(["\\", "'"], ["\\\\", "''"], (string)$v) . "'";
}
function b($v): string { return in_array(strtolower((string)$v), ['1', 'true', 'yes'], true) ? '1' : '0'; }
function n($v, $default = 0) { return ($v === '' || $v === null) ? $default : (is_numeric($v) ? $v + 0 : $default); }
function dt($v): string { if (!$v) return 'NOW()'; return "'" . substr(str_replace('T', ' ', (string)$v), 0, 19) . "'"; }
function jsonArr($v): ?string {
    if (is_array($v)) return json_encode(array_values($v), JSON_UNESCAPED_UNICODE);
    if ($v === '' || $v === null) return null;
    $d = json_decode((string)$v, true);
    return is_array($d) ? json_encode(array_values($d), JSON_UNESCAPED_UNICODE) : null;
}
function localizeImage(?string $url, string $uploadDir, array &$map): ?string {
    if (!$url) return null;
    if (isset($map[$url])) return $map[$url];
    if (!preg_match('~^https?://~', $url)) return $url;
    $name = basename(parse_url($url, PHP_URL_PATH) ?: '');
    $name = preg_replace('/[^A-Za-z0-9._-]/', '_', $name) ?: ('img_' . substr(md5($url), 0, 10) . '.png');
    $dest = "$uploadDir/$name";
    if (!is_file($dest)) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [CURLOPT_RETURNTRANSFER => true, CURLOPT_FOLLOWLOCATION => true, CURLOPT_TIMEOUT => 30, CURLOPT_USERAGENT => 'icodic-migrator']);
        $data = curl_exec($ch);
        $code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);
        if ($data && $code === 200) file_put_contents($dest, $data);
        else { fwrite(STDERR, "WARN could not download $url ($code)\n"); return $map[$url] = $url; }
    }
    return $map[$url] = '/uploads/migrated/' . $name;
}

